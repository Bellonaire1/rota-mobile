const SUPPORTED_CURRENCIES = new Set<PaystackCurrency>(['USD', 'NGN', 'GHS', 'ZAR', 'KES']);
const REFERENCE_PATTERN = /^[A-Za-z0-9.=-]{8,100}$/;
const IDEMPOTENCY_PATTERN = /^[A-Za-z0-9._:-]{8,128}$/;
export const PAYSTACK_CUSTOMER_CODE_PATTERN = /^CUS_[A-Za-z0-9._:-]{3,100}$/;
export const PAYSTACK_PLAN_CODE_PATTERN = /^PLN_[A-Za-z0-9._:-]{3,100}$/;
export const PAYSTACK_SUBSCRIPTION_CODE_PATTERN = /^SUB_[A-Za-z0-9._:-]{3,100}$/;
export const PAYSTACK_USD_MINIMUM_CENTS = 200;
const PAYSTACK_API_ORIGIN = 'https://api.paystack.co';
const PAYSTACK_CHECKOUT_ORIGIN = 'https://checkout.paystack.com';

const assertAmount = (amountCents: number, currency: PaystackCurrency): void => {
  if (!Number.isSafeInteger(amountCents) || amountCents <= 0) {
    throw new PaymentGatewayError('VALIDATION', 'Payment amount must be a positive integer in cents');
  }
  if (currency === 'USD' && amountCents < PAYSTACK_USD_MINIMUM_CENTS) {
    throw new PaymentGatewayError('VALIDATION', 'Payment amount is below the Paystack USD minimum');
  }
};

const assertCurrency: (currency: string) => asserts currency is PaystackCurrency = (currency) => {
  if (!SUPPORTED_CURRENCIES.has(currency as PaystackCurrency)) {
    throw new PaymentGatewayError('VALIDATION', 'Unsupported payment currency');
  }
};

const assertReference: (reference: string) => void = (reference) => {
  if (!REFERENCE_PATTERN.test(reference)) {
    throw new PaymentGatewayError('VALIDATION', 'Payment reference has an invalid format');
  }
};

const assertIdempotencyKey = (idempotencyKey: string): void => {
  if (!IDEMPOTENCY_PATTERN.test(idempotencyKey)) {
    throw new PaymentGatewayError('VALIDATION', 'Idempotency key has an invalid format');
  }
};

const assertMetadata = (metadata: PaymentMetadata | undefined): void => {
  if (!metadata) return;
  if (typeof metadata !== 'object' || Array.isArray(metadata)
    || Object.values(metadata).some((value) => typeof value !== 'string')) {
    throw new PaymentGatewayError('VALIDATION', 'Payment metadata is invalid');
  }
};

const metadataMatches = (actual: unknown, expected: PaymentMetadata): boolean =>
  typeof actual === 'object' && actual !== null && !Array.isArray(actual)
  && Object.entries(expected).every(([key, value]) =>
    (actual as Record<string, unknown>)[key] === value
  );

const sameMetadata = (left: PaymentMetadata | undefined, right: PaymentMetadata | undefined): boolean =>
  JSON.stringify(left ?? {}) === JSON.stringify(right ?? {});

const samePlan = (
  left: PlanInitializationOptions | undefined,
  right: PlanInitializationOptions | undefined
): boolean => {
  if (!left && !right) return true;
  if (!left || !right) return false;
  return left.planCode === right.planCode
    && left.expectedAmountCents === right.expectedAmountCents
    && left.expectedCurrency === right.expectedCurrency
    && left.expectedInterval === right.expectedInterval
    && left.expectedName === right.expectedName;
};

const validateFetchPlanByCodeInput = (input: FetchPlanByCodeInput): void => {
  if (typeof input.planCode !== 'string' || !PAYSTACK_PLAN_CODE_PATTERN.test(input.planCode)) {
    throw new PaymentGatewayError('VALIDATION', 'Plan code has an invalid format');
  }
  if (input.expectedCurrency !== 'USD') {
    throw new PaymentGatewayError('VALIDATION', 'Only USD currency is supported for plans');
  }
  if (input.expectedInterval !== 'monthly') {
    throw new PaymentGatewayError('VALIDATION', 'Only monthly interval is supported');
  }
  assertAmount(input.expectedAmountCents, input.expectedCurrency);
  if (!input.expectedName || typeof input.expectedName !== 'string' || input.expectedName.trim().length === 0 || input.expectedName.length > 100) {
    throw new PaymentGatewayError('VALIDATION', 'Plan name is invalid');
  }
};

const validateFetchSubscriptionByCodeInput = (input: FetchSubscriptionByCodeInput): void => {
  if (typeof input.subscriptionCode !== 'string' || !PAYSTACK_SUBSCRIPTION_CODE_PATTERN.test(input.subscriptionCode)) {
    throw new PaymentGatewayError('VALIDATION', 'Subscription code has an invalid format');
  }
  if (typeof input.expectedPlanCode !== 'string' || !PAYSTACK_PLAN_CODE_PATTERN.test(input.expectedPlanCode)) {
    throw new PaymentGatewayError('VALIDATION', 'Plan code has an invalid format');
  }
  if (typeof input.expectedCustomerCode !== 'string' || !PAYSTACK_CUSTOMER_CODE_PATTERN.test(input.expectedCustomerCode)) {
    throw new PaymentGatewayError('VALIDATION', 'Customer code has an invalid format');
  }
  if (input.expectedCurrency !== 'USD') {
    throw new PaymentGatewayError('VALIDATION', 'Only USD currency is supported for subscriptions');
  }
  if (input.expectedInterval !== 'monthly') {
    throw new PaymentGatewayError('VALIDATION', 'Only monthly interval is supported');
  }
  assertAmount(input.expectedAmountCents, input.expectedCurrency);
};

const validateInitializationInput = (input: InitializePaymentInput): void => {
  assertCurrency(input.currency);
  assertAmount(input.amountCents, input.currency);
  assertReference(input.reference);
  assertIdempotencyKey(input.idempotencyKey);
  assertMetadata(input.metadata);
  if (!/^\S+@\S+\.\S+$/.test(input.customerEmail)) {
    throw new PaymentGatewayError('VALIDATION', 'Customer email is invalid');
  }
  if (input.plan !== undefined) {
    if (typeof input.plan !== 'object' || input.plan === null || Array.isArray(input.plan)) {
      throw new PaymentGatewayError('VALIDATION', 'Plan configuration is invalid');
    }
    validateFetchPlanByCodeInput(input.plan);
    if (input.plan.expectedCurrency !== input.currency) {
      throw new PaymentGatewayError('VALIDATION', 'Payment currency must match the expected plan currency');
    }
    if (input.plan.expectedAmountCents !== input.amountCents) {
      throw new PaymentGatewayError('VALIDATION', 'Payment amount must match the expected plan amount');
    }
  }
};

const validateVerificationInput = (input: VerifyPaymentInput): void => {
  assertCurrency(input.expectedCurrency);
  assertAmount(input.expectedAmountCents, input.expectedCurrency);
  assertReference(input.reference);
  assertMetadata(input.expectedMetadata);
};

const validateCreatePlanInput = (input: CreatePlanInput): void => {
  if (input.currency !== 'USD') {
    throw new PaymentGatewayError('VALIDATION', 'Only USD currency is supported for plans');
  }
  if (input.interval !== 'monthly') {
    throw new PaymentGatewayError('VALIDATION', 'Only monthly interval is supported');
  }
  assertAmount(input.amountCents, input.currency);
  if (!input.name || typeof input.name !== 'string' || input.name.trim().length === 0 || input.name.length > 100) {
    throw new PaymentGatewayError('VALIDATION', 'Plan name is invalid');
  }
  if (input.description !== undefined) {
    if (typeof input.description !== 'string' || input.description.length > 255) {
      throw new PaymentGatewayError('VALIDATION', 'Plan description is invalid');
    }
  }
};

