export type PaystackCurrency = 'USD' | 'NGN' | 'GHS' | 'ZAR' | 'KES';

export type PaymentGatewayErrorCode =
  | 'CONFIGURATION'
  | 'VALIDATION'
  | 'DUPLICATE_OPERATION'
  | 'TIMEOUT'
  | 'NETWORK'
  | 'HTTP'
  | 'INVALID_RESPONSE'
  | 'PROVIDER_FAILURE'
  | 'VERIFICATION_MISMATCH';

export class PaymentGatewayError extends Error {
  constructor(
    public readonly code: PaymentGatewayErrorCode,
    message: string
  ) {
    super(message);
    this.name = 'PaymentGatewayError';
  }
}

